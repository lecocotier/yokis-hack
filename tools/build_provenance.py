"""Public, byte-based build identity and artifact receipts.

This module is also a PlatformIO ``pre:`` extra script. Public identity inputs
are src/include/lib files, platformio.ini, and tools/scripts build scripts.
Private/local configuration, generated files, tests, tools caches, and build
products are explicitly excluded. Neither headers nor receipts publish absolute
paths, configuration contents, compiler flags, credentials, or network addresses.

The digest covers exact working-tree bytes, including line endings. Two Git
checkouts with different autocrlf settings can therefore have different public
source digests even at the same revision: they do not supply identical bytes to
the compiler. Installed dependency versions are metadata, not source-byte proof.
"""

import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
from typing import Any, Iterable, Mapping


_SOURCE_DIRECTORIES = ("src", "include", "lib")
_SCRIPT_DIRECTORIES = ("tools", "scripts")
_SCRIPT_SUFFIXES = {".py", ".ps1", ".sh", ".cmd", ".bat", ".cmake"}
_EXCLUDED_COMPONENTS = {
    "build", "dist", "test", "tests", "generated", "autogenerated",
    "__pycache__", "node_modules", "venv",
}
_EXCLUDED_SUFFIXES = {
    ".a", ".bin", ".d", ".elf", ".log", ".map", ".o", ".pyc", ".pyo",
    ".tmp", ".bak",
}
_PRIVATE_NAME = re.compile(
    r"(?:^|[._-])(?:private|local|secrets?|credentials?)(?:[._-]|$)", re.I
)
_REVISION = re.compile(r"(?:[a-f0-9]{40}|[a-f0-9]{64})\Z")
_SHA256 = re.compile(r"[a-f0-9]{64}\Z")
_NAME = re.compile(r"[A-Za-z][A-Za-z0-9_+.-]{0,95}\Z")
_VERSION = re.compile(r"[0-9]+(?:\.[0-9]+){0,2}(?:[-+][A-Za-z0-9][A-Za-z0-9.+-]*)?\Z")
_IP_LIKE = re.compile(r"(?:[0-9]{1,3}\.){3}[0-9]{1,3}")
EXCLUSIONS = (
    "Private/local configuration and secret/credential paths are excluded.",
    "Generated files, tests, build outputs, .pio and .tools caches are excluded.",
    "Symlinks/junctions and installed dependency bytes are excluded.",
)
BYTE_POLICY = "Exact public working-tree bytes; no line-ending normalization."


def _project_root(root: Path | str) -> Path:
    result = Path(root).resolve()
    if not result.is_dir():
        raise ValueError("Source root must be an existing directory")
    return result


def _excluded_name(name: str) -> bool:
    lower = name.casefold()
    return (
        lower.startswith(".")
        or lower in _EXCLUDED_COMPONENTS
        or lower == "build_provenance.h"
        or bool(_PRIVATE_NAME.search(lower))
    )


def _ordinary_path(path: Path, root: Path) -> bool:
    """Do not follow public-looking aliases into private or external files."""
    try:
        if path.is_symlink():
            return False
        is_junction = getattr(path, "is_junction", None)
        if is_junction is not None and is_junction():
            return False
        path.resolve().relative_to(root)
        return True
    except (OSError, ValueError):
        return False


def _walk_inputs(root: Path, directory: str, scripts_only: bool) -> Iterable[Path]:
    base = root / directory
    if not base.is_dir() or not _ordinary_path(base, root):
        return

    def enumeration_error(_error: OSError) -> None:
        raise RuntimeError("Cannot enumerate public source inputs") from None

    for current, directories, filenames in os.walk(
        base, topdown=True, followlinks=False, onerror=enumeration_error
    ):
        current_path = Path(current)
        directories[:] = [
            name for name in directories
            if not _excluded_name(name) and _ordinary_path(current_path / name, root)
        ]
        for name in filenames:
            path = current_path / name
            if _excluded_name(name) or path.suffix.casefold() in _EXCLUDED_SUFFIXES:
                continue
            if scripts_only and path.suffix.casefold() not in _SCRIPT_SUFFIXES:
                continue
            if _ordinary_path(path, root) and path.is_file():
                yield path


def _source_digest(root: Path) -> tuple[str, int]:
    paths = []
    platformio = root / "platformio.ini"
    if platformio.is_file() and _ordinary_path(platformio, root):
        paths.append(platformio)
    for directory in _SOURCE_DIRECTORIES:
        paths.extend(_walk_inputs(root, directory, scripts_only=False))
    for directory in _SCRIPT_DIRECTORIES:
        paths.extend(_walk_inputs(root, directory, scripts_only=True))
    ordered = sorted(paths, key=lambda path: path.relative_to(root).as_posix())
    digest = hashlib.sha256(b"yokis-public-source-v1\x00")
    for path in ordered:
        relative = path.relative_to(root).as_posix().encode("utf-8")
        contents = path.read_bytes()
        # Length-delimited paths and data avoid concatenation ambiguities.
        digest.update(len(relative).to_bytes(8, "big"))
        digest.update(relative)
        digest.update(len(contents).to_bytes(8, "big"))
        digest.update(contents)
    return digest.hexdigest(), len(ordered)


def _git_identity(root: Path) -> tuple[str | None, bool | None]:
    command = [
        "git", "--no-optional-locks", "-c", "safe.directory=" + str(root),
        "-C", str(root),
    ]
    try:
        revision = subprocess.run(
            command + ["rev-parse", "--verify", "HEAD"],
            check=True, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
            text=True, timeout=10,
        ).stdout.strip().lower()
        if not _REVISION.fullmatch(revision):
            return None, None
        status = subprocess.run(
            command + ["status", "--porcelain=v1", "--untracked-files=normal"],
            check=True, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
            text=True, timeout=10,
        ).stdout
        return revision, bool(status)
    except (OSError, subprocess.SubprocessError):
        return None, None


def _validated_identity(identity: Mapping[str, Any]) -> tuple[str | None, bool | None, str, int]:
    revision = identity.get("git_revision")
    if not isinstance(revision, str) or not _REVISION.fullmatch(revision.lower()):
        revision = None
    else:
        revision = revision.lower()
    dirty = identity.get("git_dirty")
    if not isinstance(dirty, bool):
        dirty = None
    source_hash = identity.get("source_sha256")
    if not isinstance(source_hash, str) or not _SHA256.fullmatch(source_hash):
        raise ValueError("Public source SHA-256 is invalid")
    count = identity.get("source_file_count")
    if not isinstance(count, int) or isinstance(count, bool) or count < 0:
        raise ValueError("Public source file count is invalid")
    return revision, dirty, source_hash, count


def source_identity(root: Path | str) -> dict[str, Any]:
    """Return Git state plus the SHA-256 of selected public working-tree bytes."""
    project = _project_root(root)
    source_hash, count = _source_digest(project)
    revision, dirty = _git_identity(project)
    return {
        "git_revision": revision,
        "git_dirty": dirty,
        "source_sha256": source_hash,
        "source_file_count": count,
        "byte_policy": BYTE_POLICY,
        "exclusions": list(EXCLUSIONS),
    }


def render_header(identity: Mapping[str, Any]) -> str:
    """Render YOKIS_BUILD_ID, YOKIS_BUILD_GIT and YOKIS_BUILD_SOURCE_SHA256."""
    revision, dirty, source_hash, _count = _validated_identity(identity)
    git_label = revision[:12] if revision else "unknown"
    if dirty is True:
        git_label += "-dirty"
    elif dirty is None and revision:
        git_label += "-state-unknown"
    build_id = git_label + "+src." + source_hash[:12]
    return (
        "// Generated public identity. Private/local configuration is excluded.\n"
        "// Source digest covers exact bytes, including line endings.\n"
        "#pragma once\n"
        '#define YOKIS_BUILD_GIT "' + git_label + '"\n'
        '#define YOKIS_BUILD_GIT_REVISION "' + (revision or "unknown") + '"\n'
        "#define YOKIS_BUILD_GIT_DIRTY " + ("1" if dirty is True else "0" if dirty is False else "-1") + "\n"
        '#define YOKIS_BUILD_SOURCE_SHA256 "' + source_hash + '"\n'
        '#define YOKIS_BUILD_ID "' + build_id + '"\n'
    )


def _safe_name(value: Any) -> str | None:
    if (
        isinstance(value, str) and _NAME.fullmatch(value)
        and not _IP_LIKE.search(value) and not _PRIVATE_NAME.search(value)
    ):
        return value
    return None


def _safe_package(value: Any) -> dict[str, str] | None:
    if not isinstance(value, Mapping):
        return None
    name = _safe_name(value.get("name"))
    version = value.get("version")
    if (
        name is not None and isinstance(version, str)
        and _VERSION.fullmatch(version) and not _IP_LIKE.search(version)
    ):
        return {"name": name, "version": version}
    return None


def _safe_metadata(metadata: Mapping[str, Any] | None) -> dict[str, Any]:
    result: dict[str, Any] = {}
    if not isinstance(metadata, Mapping):
        return result
    for key in ("platform", "compiler", "framework"):
        package = _safe_package(metadata.get(key))
        if package is not None:
            result[key] = package
    dependencies = metadata.get("dependencies")
    if isinstance(dependencies, (list, tuple)):
        packages = {}
        for item in dependencies:
            package = _safe_package(item)
            if package is not None:
                packages[(package["name"], package["version"])] = package
        result["dependencies"] = [packages[key] for key in sorted(packages)]
    return result


def _atomic_write(path: Path, contents: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_file() and path.read_bytes() == contents:
        return
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(
            prefix=".provenance-", suffix=".tmp", dir=path.parent, delete=False
        ) as stream:
            temporary = Path(stream.name)
            stream.write(contents)
        os.replace(temporary, path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def write_receipt(
    root: Path | str,
    builddir: Path | str,
    identity: Mapping[str, Any],
    binaries: Iterable[Path | str],
    environment: str,
    metadata: Mapping[str, Any] | None = None,
) -> Path:
    """Write build-receipt.json, returning its path; retain safe metadata only."""
    project = _project_root(root)
    directory = Path(builddir)
    if not directory.is_absolute():
        directory = project / directory
    directory = directory.resolve()
    try:
        directory.relative_to(project)
    except ValueError:
        raise ValueError("Build directory must be inside the project root") from None
    safe_environment = _safe_name(environment)
    if safe_environment is None:
        raise ValueError("Build environment name is invalid")
    revision, dirty, source_hash, count = _validated_identity(identity)
    artifacts = []
    seen_names = set()
    for binary in binaries:
        path = Path(binary)
        if not path.is_absolute():
            path = directory / path
        try:
            path.resolve().relative_to(directory)
        except ValueError:
            raise ValueError("Artifact must be inside the build directory") from None
        if not _ordinary_path(path, directory) or not path.is_file():
            raise ValueError("Artifact must be an existing ordinary build file")
        if path.suffix.casefold() not in {".bin", ".elf", ".hex"} or _safe_name(path.name) is None:
            raise ValueError("Artifact name is invalid")
        if path.name in seen_names:
            raise ValueError("Artifact names must be unique")
        seen_names.add(path.name)
        digest = hashlib.sha256()
        size = 0
        with path.open("rb") as stream:
            for chunk in iter(lambda: stream.read(1024 * 1024), b""):
                digest.update(chunk)
                size += len(chunk)
        artifacts.append({"name": path.name, "sha256": digest.hexdigest(), "size": size})
    if not artifacts:
        raise ValueError("A build receipt requires at least one artifact")
    if _source_digest(project) != (source_hash, count):
        raise RuntimeError("Public source inputs changed during the build; rebuild before publishing a receipt")
    receipt = {
        "schema_version": 1,
        "environment": safe_environment,
        "git": {"revision": revision, "dirty": dirty},
        "source": {
            "sha256": source_hash, "file_count": count,
            "byte_policy": BYTE_POLICY, "exclusions": list(EXCLUSIONS),
        },
        "artifacts": sorted(artifacts, key=lambda item: item["name"]),
        "metadata": _safe_metadata(metadata),
    }
    target = directory / "build-receipt.json"
    _atomic_write(target, (json.dumps(receipt, indent=2, sort_keys=True) + "\n").encode("utf-8"))
    return target


def _package_manifest(directory: Any, filename: str) -> dict[str, str] | None:
    if not directory:
        return None
    try:
        manifest = json.loads((Path(directory) / filename).read_text(encoding="utf-8"))
        return _safe_package(manifest)
    except (OSError, TypeError, ValueError):
        return None


def _collect_metadata(environment: Any, project: Path, name: str) -> dict[str, Any]:
    """Read only known package/version fields, never allenv or build flags."""
    metadata: dict[str, Any] = {}
    try:
        platform = environment.PioPlatform()
        package = _package_manifest(platform.get_dir(), "platform.json")
        if package:
            metadata["platform"] = package
        for framework in ("framework-arduinoespressif8266", "framework-arduino-avr"):
            try:
                directory = platform.get_package_dir(framework)
            except KeyError:  # Package belongs to the other supported platform.
                continue
            package = _package_manifest(directory, "package.json")
            if package:
                metadata["framework"] = package
                break
    except (AttributeError, OSError, TypeError, ValueError, KeyError):
        pass
    try:
        compiler = str(environment.subst("$CXX"))
        if compiler.startswith('"') and compiler.endswith('"'):
            compiler = compiler[1:-1]
        compiler_name = _safe_name(Path(compiler).stem)
        if compiler_name and "\n" not in compiler and "\r" not in compiler:
            output = subprocess.run(
                [compiler, "--version"], check=True, stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL, text=True, timeout=10,
            ).stdout
            first_line = output.splitlines()[0] if output else ""
            version = re.search(r"\b([0-9]+\.[0-9]+(?:\.[0-9]+)?)\b", first_line)
            package = _safe_package({
                "name": compiler_name, "version": version.group(1) if version else None,
            })
            if package:
                metadata["compiler"] = package
    except (AttributeError, OSError, TypeError, ValueError, subprocess.SubprocessError):
        pass
    dependencies = []
    try:
        configured = str(environment.subst("$PROJECT_LIBDEPS_DIR"))
        libdeps = Path(configured) if "$" not in configured else project / ".pio/libdeps"
        if not libdeps.is_absolute():
            libdeps = project / libdeps
        directory = libdeps / name
        if directory.is_dir():
            for child in sorted(directory.iterdir()):
                if not child.is_dir() or child.is_symlink() or child.name.startswith("."):
                    continue
                package = _package_manifest(child, "library.json")
                if package is None:
                    properties = child / "library.properties"
                    if properties.is_file():
                        values = {}
                        for line in properties.read_text(encoding="utf-8").splitlines():
                            key, separator, value = line.partition("=")
                            if separator and key.strip() in {"name", "version"}:
                                values[key.strip()] = value.strip()
                        package = _safe_package(values)
                if package:
                    dependencies.append(package)
    except (AttributeError, OSError, TypeError, ValueError):
        pass
    metadata["dependencies"] = dependencies
    return _safe_metadata(metadata)


def _configure_platformio(environment: Any) -> None:
    """Install generated-header and post-link/post-binary receipt actions."""
    project = _project_root(environment.subst("$PROJECT_DIR"))
    identity = source_identity(project)
    _atomic_write(project / "include/build_provenance.h", render_header(identity).encode("utf-8"))
    builddir = Path(environment.subst("$BUILD_DIR"))
    if not builddir.is_absolute():
        builddir = project / builddir
    builddir = builddir.resolve()
    name = str(environment.get("PIOENV", "unknown"))
    # PROGNAME is not initialized yet by PlatformIO at pre-script time.
    # The post-action's concrete target is the authoritative artifact path.
    def artifact(target: Any) -> Path:
        if not target:
            raise ValueError("Build receipt action has no artifact target")
        path = Path(str(target[0]))
        return path if path.is_absolute() else project / path

    def after_elf(source: Any, target: Any, env: Any) -> None:
        # An old BIN may still exist here. Never attribute it to this ELF.
        write_receipt(
            project, builddir, identity, [artifact(target)], name,
            _collect_metadata(env, project, name),
        )

    def after_bin(source: Any, target: Any, env: Any) -> None:
        binary = artifact(target)
        artifacts = [binary]
        elf = binary.with_suffix(".elf")
        if elf.is_file():
            artifacts.append(elf)
        write_receipt(
            project, builddir, identity, artifacts, name,
            _collect_metadata(env, project, name),
        )

    environment.AddPostAction("$BUILD_DIR/${PROGNAME}.elf", after_elf)
    environment.AddPostAction("$BUILD_DIR/${PROGNAME}.bin", after_bin)
    environment.AddPostAction("$BUILD_DIR/${PROGNAME}.hex", after_bin)


if "Import" in globals():
    Import("env")  # type: ignore[name-defined]  # SCons extra-script injection.
    _configure_platformio(env)  # type: ignore[name-defined]
